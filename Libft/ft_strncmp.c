#include "libft.h"

int	ft_strncmp(const char *s1, const char *s2, size_t n)
{
	int i;
	int j;

	i = 0;
	j = 0;
	while (s1[i] == s2[j] && s1[i] != '\0' &&  --n)
	{
	
		i++;
		j++;
	}
	return (s1[i] - s2[j]);
}

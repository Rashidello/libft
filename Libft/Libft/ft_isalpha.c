#include <libft.h>

int	ft_isalpha(int c)
{
	unsigned char	ch;

	ch = c;
	if ((ch >= 'a' && ch <= 'z') || (ch >= "A" && ch <= "Z"))
		return (1);
	else
		return (0);
}

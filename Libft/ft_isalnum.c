#include "libft.h"

int	ft_isalnum(int c)
{
	unsigned char	ver;

	ver = c;
	if ((ver >= '0' && ver <= '9') || (ver >= 'a' && ver <= 'z')
		|| (ver >= 'A' && ver <= 'Z'))
		return (1);
	return (0);
}
